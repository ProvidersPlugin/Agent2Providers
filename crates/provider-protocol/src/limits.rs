//! 协议常量：版本号、分帧上限、背压窗口。
//!
//! ── 为什么这些数字要放在协议 crate 里而不是各自实现里 ────────────
//! 它们是**双方共同遵守的约定**：网关按 [`MAX_LINE_BYTES`] 判定「这个子进程
//! 坏了」，插件也按同一个数决定「这一帧要不要拆」。两边各写一份的下场是
//! 一边以为能发、另一边判定超限并杀掉进程 —— 而那种故障在本地开发时几乎
//! 不会出现（只有大响应才触发），上线后才炸。

/// 协议版本。握手时双方交换，不一致一律拒绝加载。
///
/// ── 什么时候必须升 ──────────────────────────────────────────
///   - 删字段 / 改字段语义 / 把可选改必填；
///   - 新增必填字段；
///   - 改变某个方法的行为契约（例如 `chat` 从「一次请求一次回复」变成
///     「允许中途续帧」）。
///
/// ── 什么时候不用升 ──────────────────────────────────────────
///   - 新增**可选**字段（`Option` 或带 serde 默认值）；
///   - 新增方法（旧插件不实现时，网关按「不支持」处理，见 `methods`）；
///   - 新增枚举变体**且**双方都按 `#[serde(other)]` 兜底。
pub const PROTOCOL_VERSION: u32 = 1;

/// 一行的字节上限（含行尾换行）。
///
/// 超限的读法有两种，都是**致命**的：读循环直接判定对端坏了并杀进程。
/// 这不是保守 —— 一个不结束一行的子进程能让父进程无界分配内存，而
/// `panic = "abort"` 下 OOM 就是整个桌面应用消失。
///
/// 取 16 MiB：够容纳「一次性返回整个模型目录」这类控制面消息（最大的
/// provider 目录约 2000 条记录、约 1.5 MB JSON），又远小于流式数据的量级
/// —— 流式数据必须走 chunk 帧，不能挤在一个 result 里。
pub const MAX_LINE_BYTES: usize = 16 << 20;

/// 单个流式 chunk 的载荷上限（解码后）。
///
/// 插件发 chunk 前必须自行切分；网关收到超过这个数的 chunk 不视为错误
/// （仍会转发），但会记一条警告 —— 因为它意味着插件没按背压窗口来。
pub const MAX_CHUNK_BYTES: usize = 64 << 10;

/// 一帧的**计费**开销（字节）。
///
/// 背压窗口按「载荷 + 这个常数」计费：帧本身的 JSON 包装、base64 膨胀、
/// 字段名都要占内存，只按载荷算会让窗口在高频小帧时严重低估。取 2 KiB
/// 是因为实测一个 `{id,event,data}` 帧的包装在 200–800 字节之间，留了余量。
pub const FRAME_OVERHEAD_BYTES: usize = 2048;

/// 一次流式调用的初始信用窗口（字节）。
///
/// ── 这个数是干什么的（背压的核心）───────────────────────────
/// 插件在收到 `credit` 之前，最多只能发送这么多**已计费字节**。网关每从
/// 流里读走一段，就回一个 `credit{n}` 把额度还回去。于是：
///   - 客户端读得慢 → 网关不还额度 → 插件停在写操作上 → 上游 TCP 窗口
///     收缩 → 真正的背压一路传回上游；
///   - 没有这个窗口，一个卡住的客户端会让插件把整段回答缓冲在内存里。
///
/// 取 512 KiB：约 8 个满尺寸 chunk。太小会让高速流退化成「发一帧等一次
/// 往返」；太大则失去背压意义（512 KiB × 50 并发 = 25 MB 缓冲上限，可接受）。
pub const DEFAULT_WINDOW_BYTES: usize = 512 << 10;
