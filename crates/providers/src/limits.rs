//! 各家共用的长度上限常量。
//!
//! ── 为什么集中一处 ──────────────────────────────────────────
//! 从网关搬来的几家 `credentials.rs` 都引用 `account_store::MAX_TOKEN_LENGTH`
//! 做「用户粘贴的东西是不是贴错了」的粗检。插件里没有那个模块（账号存储
//! 在网关侧），但这些判据本身与存储无关 —— 集中在这里，各家引用同一份值。

/// token 长度上限（与网关 `account_store::MAX_TOKEN_LENGTH` 同值）。
///
/// 超出这个长度的输入一定是粘错了东西（整段 JSON / 整个页面）。
pub const MAX_TOKEN_LENGTH: usize = 8192;
