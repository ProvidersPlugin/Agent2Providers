//! WorkBuddy 的**跨家共用层**：端点表、客户端身份、版本号。
//!
//! ── 为什么单独一个目录 ──────────────────────────────────────
//! 网关里这些常量住在 `core::endpoints`（它是**整个网关**的端点事实来源：
//! 登录、鉴权、计费、成长任务、保活五处都从那里取）。插件侧只有 workbuddy
//! 一家用它们，但用量覆盖了 `region` / `auth` / `billing` / `catalog` 四个模块 ——
//! 放在 `providers/workbuddy/endpoints.rs` 会让「谁引用谁」看起来像
//! provider 内部细节，而实际上它是**上游契约**（站点、UA、版本号是腾讯下发的
//! 客户端身份，不随我们的 provider 结构变）。
//!
//! ── 内容来源 ────────────────────────────────────────────────
//! 逐字复制自网关 `server::core::endpoints`（模块级 `allow(dead_code)` 已去掉
//! 的那部分：`*_endpoints()` 那几张表在插件里没有消费方，但保留它们能让
//! 「与网关逐行对照」这件事继续成立）。
//!
//! ── 硬约束 ──────────────────────────────────────────────────
//! release 是 `panic=abort`：本目录零 unwrap/expect/panic。

pub mod endpoints;
